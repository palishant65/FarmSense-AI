export const dict = { en, hi, bn, mr, te };

export function t(lang, key, vars) {
  const L = dict[lang] || en;
  return fill(L[key] || en[key] || key, vars);
}

export function cropKey(name) {
  const n = String(name || "").toLowerCase();
  if (n.includes("wheat") || n.includes("गेहूँ") || n.includes("गेहूं")) return "crop.wheat";
  if (n.includes("potato") || n.includes("आलू")) return "crop.potato";
  return "crop.tomato";
}

export function stageKey(stage) {
  const s = String(stage || "");
  if (/tiller/i.test(s)) return "stage.tillering";
  if (/tuber/i.test(s)) return "stage.tuber";
  return "stage.fruit";
}

export function localizeScan(s, tt) {
  if (!s) return s;
  return {
    ...s,
    name: s.nameKey ? tt(s.nameKey) : s.name,
    severity: s.severityKey ? tt(s.severityKey) : s.severity,
    symptoms: s.symptomsKey ? tt(s.symptomsKey) : s.symptoms,
    causes: s.causesKey ? tt(s.causesKey) : s.causes,
    actions: (s.actionKeys || s.actions || []).map((k) => (String(k).startsWith("dis.") ? tt(k) : k)),
    disclaimer: s.disclaimerKey ? tt(s.disclaimerKey) : s.disclaimer,
    field: `${tt("ui.field")} A — ${tt(cropKey(s.crop || "Tomato"))}`,
  };
}

export function applyI18nToRec(rec, tt) {
  if (!rec) return rec;
  const crop = tt(cropKey(rec.crop?.name));
  let recommendation = rec.recommendation;
  if (rec.action === "delay") recommendation = tt("rec.delay", { n: rec.delayHours });
  else if (rec.action === "skip") recommendation = tt("rec.skip");
  else if (rec.action === "optimize") recommendation = tt("rec.optimize");
  else if (String(rec.recommendation || "").toLowerCase().includes("critical")) recommendation = tt("rec.critical");
  else recommendation = tt("rec.now");
  const saved = rec.impact?.waterSavedL ? tt("rec.savedTail", { n: rec.impact.waterSavedL }) : "";
  const reason = tt("rec.reason", {
    rain: rec.weather?.rainProb, moisture: rec.soil?.moisture, crop, rec: recommendation, saved,
  });
  const fmap = {
    "Rain probability": "ui.rainChance",
    "Soil moisture": "irr.moist",
    Crop: "nav.crops",
    "Growth stage": "ui.stage",
    Temperature: "ui.temp",
    "Market signal": "nav.market",
  };
  const factors = (rec.factors || []).map((f) => {
    const k = fmap[f.key] ? tt(fmap[f.key]) : f.key;
    let value = f.value;
    if (f.key === "Crop") value = crop;
    if (f.key === "Growth stage") value = tt(stageKey(rec.crop?.stage));
    return { ...f, key: k, value };
  });
  const next = rec.nextIrrigation === "Now" ? tt("ui.now") : rec.nextIrrigation;
  return {
    ...rec,
    recommendation,
    reason,
    factors,
    nextIrrigation: next,
    crop: { ...rec.crop, label: crop, stageLabel: tt(stageKey(rec.crop?.stage)) },
    weather: { ...rec.weather, condition: tt("wx.cloudy") },
    soil: { ...rec.soil, textureLabel: tt("soil.loam") },
    market: {
      ...rec.market,
      trendLabel: rec.market?.trend === "up" ? tt("ui.trendUp") : tt("ui.trendDown"),
    },
  };
}
